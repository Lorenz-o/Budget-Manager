/** Restituisce l'etichetta tradotta nella lingua data (fallback: originale). */
export function translateLabel(lang: Lang, label?: string | null): string {
  if (!label) return '';
  const key = LABEL_KEYS[label.trim()];
  return key ? translate(lang, key) : label;
}

